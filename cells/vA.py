def stretch(wav, speed):
    if not USE_SPEED or abs(speed - 1.0) < 0.01: return wav
    y = librosa.effects.time_stretch(wav.squeeze(0).cpu().numpy(), rate=speed)
    return torch.from_numpy(np.ascontiguousarray(y)).unsqueeze(0)

